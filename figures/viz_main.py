"""
@brief Visualization script for THB-spline mesh data generated by G+Smo.

This script reads mesh files exported by the generateVisualizationMesh function
of the research code (poissonTHB_example.cpp), or in the same format by
examples/export_visualization_mesh of this module, and visualizes the
parametric grid lines in 2D.

"""

