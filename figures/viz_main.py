def draw_interface_diagnostics(ax,
                               interface_metadata: List[Dict[str, object]],
                               all_lines: List[np.ndarray],
                               arrow_scale: float = 0.045,
                               gap_label_threshold: float = 1e-3) -> None:
    """! Draw interface midpoint tangents and the geometric gap between both sides."""
    if not interface_metadata or not all_lines:
        return

    all_points = np.vstack(all_lines)
    extent = np.max(all_points, axis=0) - np.min(all_points, axis=0)
    base_length = arrow_scale * np.linalg.norm(extent)
    if base_length <= 0:
        base_length = 0.08

    for info in interface_metadata:
        midpoint_a = info['midpoint_a']
        midpoint_b = info['midpoint_b']
        tangent_a = info['tangent_a']
        tangent_b = info['tangent_b']
        gap = info['gap']
        patch_a = info['patch_a']
        patch_b = info['patch_b']
        side_a = info['side_a']
        side_b = info['side_b']
        reversed_orientation = info['reversed']

        has_gap = gap > gap_label_threshold

        # Only annotate interfaces that have a real gap; skip-zero ones silently.
        if not has_gap:
            continue

        ax.plot([midpoint_a[0], midpoint_b[0]],
                [midpoint_a[1], midpoint_b[1]],
                color='crimson',
                linewidth=1.2,
                linestyle=':',
                alpha=0.85,
                zorder=15)

        ax.annotate('',
                    xy=midpoint_a + base_length * tangent_a,
                    xytext=midpoint_a,
                    arrowprops=dict(arrowstyle='->', color='navy', lw=1.2),
                    zorder=16)
        ax.annotate('',
                    xy=midpoint_b + base_length * tangent_b,
                    xytext=midpoint_b,
                    arrowprops=dict(arrowstyle='->', color='darkorange', lw=1.2),
                    zorder=16)

        ax.scatter([midpoint_a[0], midpoint_b[0]],
                   [midpoint_a[1], midpoint_b[1]],
                   s=18,
                   color=['navy', 'darkorange'],
                   zorder=17)

        label_mid = 0.5 * (midpoint_a + midpoint_b)
        orientation_label = 'rev' if reversed_orientation else 'same'
        ax.text(label_mid[0], label_mid[1],
                f'{patch_a}:{side_a} | {patch_b}:{side_b}\n{orientation_label}, gap={gap:.3e}',
                fontsize=6,
                color='black',
                ha='center',
                va='bottom',
                bbox=dict(boxstyle='round,pad=0.18', facecolor='white', edgecolor='gray', alpha=0.78),
                zorder=18)




# --------------------------------------------------------------------------
# Patch colouring (Issues 1 + 4)
# --------------------------------------------------------------------------
# Bright, well-separated hues.  Consecutive entries are far apart in hue, so a
# run of low palette indices still reads as clearly distinct.  Yellow / light
# tints are deliberately absent: thin light lines are unreadable on white
# paper.  Seven hues are enough for a proper colouring of any planar patch
# adjacency graph (planar graphs are 5-degenerate, so the greedy pass below
# never needs more than six).
PATCH_PALETTE: List[str] = [
    '#e6194b',  # crimson
    '#3a6fe0',  # blue
    '#1a9e2e',  # green
    '#f032e6',  # magenta
    '#f58231',  # orange
    '#00a3a3',  # teal
    '#8b2fd1',  # violet
]


def build_patch_adjacency(unique_patches: List[int],
                          interface_metadata: Optional[List[Dict[str, object]]]
                          ) -> Dict[int, set]:
    """! Patch adjacency graph taken from the exported *_interface_meta.txt data.

    Each metadata record describes one shared interface (patch_a, patch_b), so
    the records are exactly the edges of the patch adjacency graph.
    """
    adjacency: Dict[int, set] = {p: set() for p in unique_patches}
    for info in interface_metadata or []:
        a = info.get('patch_a')
        b = info.get('patch_b')
        if a is None or b is None or a == b:
            continue
        if a in adjacency and b in adjacency:
            adjacency[a].add(b)
            adjacency[b].add(a)
    return adjacency


def _smallest_last_order(unique_patches: List[int],
                         adjacency: Dict[int, set]) -> List[int]:
    """! Smallest-last (degeneracy) ordering of the patches.

    Repeatedly removing a minimum-degree vertex and colouring in reverse
    removal order guarantees that every patch has at most `degeneracy`
    already-coloured neighbours when it is coloured (at most 5 for a planar
    adjacency graph).  Ties are broken by patch index, so the result is
    deterministic and both plots agree.
    """
    remaining = set(unique_patches)
    degree = {p: len(adjacency[p] & remaining) for p in remaining}
    removal: List[int] = []
    while remaining:
        v = min(remaining, key=lambda p: (degree[p], p))
        remaining.discard(v)
        removal.append(v)
        for u in adjacency[v]:
            if u in remaining:
                degree[u] -= 1
    removal.reverse()
    return removal


def build_patch_colors(unique_patches: List[int],
                       interface_metadata: Optional[List[Dict[str, object]]] = None,
                       palette: Optional[List[str]] = None) -> Dict[int, str]:
    """! Assign a colour to every patch so that no two neighbours look alike.

    Colour reuse is unavoidable once the patch count exceeds the palette size
    (joystick has 30 patches), so the requirement is that repeats never land on
    patches sharing an interface.  That is a graph-colouring problem, solved
    here with a greedy pass in smallest-last order:

    * colours used by an already-coloured neighbour are forbidden;
    * colours used by a second-order neighbour are avoided when possible, which
      keeps repeats two interfaces apart rather than one;
    * among the remaining choices the least-used colour wins, which spreads the
      palette evenly instead of collapsing onto the first few entries.

    The least-used rule also means that whenever the patch count does not
    exceed the palette size (e.g. TUDflame with 5 patches) every patch receives
    a different bright colour.

    Deterministic for a given (patch list, interface metadata) pair, so the
    mesh plot and the point-cloud plot stay consistent.
    """
    colour_list = list(palette if palette is not None else PATCH_PALETTE)
    patches = sorted(unique_patches)
    if not patches:
        return {}

    adjacency = build_patch_adjacency(patches, interface_metadata)
    if not any(adjacency.values()):
        # No interface information available: cycle the palette.  Still bright,
        # and still distinct whenever the patch count fits the palette.
        return {p: colour_list[i % len(colour_list)] for i, p in enumerate(patches)}

    assigned: Dict[int, int] = {}
    usage = [0] * len(colour_list)
    for v in _smallest_last_order(patches, adjacency):
        banned = {assigned[u] for u in adjacency[v] if u in assigned}
        second = {assigned[u] for w in adjacency[v] for u in adjacency[w]
                  if u in assigned and u != v}
        candidates = [c for c in range(len(colour_list)) if c not in banned]
        preferred = [c for c in candidates if c not in second]
        pool = preferred or candidates or list(range(len(colour_list)))
        choice = min(pool, key=lambda c: (usage[c], c))
        assigned[v] = choice
        usage[choice] += 1

    return {p: colour_list[assigned[p]] for p in patches}


