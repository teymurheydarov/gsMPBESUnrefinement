def choose_existing_file(candidates: List[str]) -> Optional[str]:
    """Return the first existing file from a list of absolute path candidates."""
    for candidate in candidates:
        if os.path.exists(candidate):
            return candidate
    return None


def normalized(vec: np.ndarray) -> np.ndarray:
    """Return a normalized copy of a 2D vector."""
    norm = np.linalg.norm(vec)
    if norm <= 1e-12:
        return np.zeros_like(vec)
    return vec / norm


def _smooth_line_for_display(line: np.ndarray, n_pts: int = 300,
                              max_sample_pts: int = 33) -> np.ndarray:
    """Return a smooth cubic spline through a (possibly kinky) polyline.

    Uses a GCV-automatic smoothing spline (scipy.interpolate.make_smoothing_spline)
    fit separately to x(t) and y(t) with chord-length parameterisation.  The GCV
    criterion averages over zigzag artefacts while preserving genuine wave shapes,
    yielding C2-smooth curves with no visible kinks regardless of the underlying
    geometry degree.

    Falls back to a simple interpolating cubic spline through 9 subsampled points
    if make_smoothing_spline is unavailable (scipy < 1.10).
    """
    if len(line) < 4:
        return line
    # Subsample dense lines before fitting so GCV has manageable input
    if len(line) > max_sample_pts:
        idx = np.round(np.linspace(0, len(line) - 1, max_sample_pts)).astype(int)
        pts = line[idx]
    else:
        pts = line
    # Chord-length parameterisation
    diffs = np.diff(pts, axis=0)
    chords = np.sqrt((diffs ** 2).sum(axis=1))
    total = chords.sum()
    if total < 1e-12:
        return line
    t = np.concatenate([[0.0], np.cumsum(chords) / total])
    t_eval = np.linspace(0.0, 1.0, n_pts)
    try:
        from scipy.interpolate import UnivariateSpline
        # High weights at the endpoints force the spline to interpolate the exact
        # hexagon corners; interior weight=1 lets it smooth over the zigzag artefact.
        w = np.ones(len(pts))
        w[0] = w[-1] = 1e4
        # s: target weighted sum-of-squares; allow ~0.01-unit RMS for interior pts.
        s = (len(pts) - 2) * 0.012 ** 2
        spl_x = UnivariateSpline(t, pts[:, 0], k=3, w=w, s=s)
        spl_y = UnivariateSpline(t, pts[:, 1], k=3, w=w, s=s)
        return np.column_stack([spl_x(t_eval), spl_y(t_eval)])
    except ImportError:
        pass
    try:
        from scipy.interpolate import make_interp_spline
        # Fallback: interpolating spline through fewer points to reduce kinks
        if len(pts) > 9:
            idx2 = np.round(np.linspace(0, len(pts) - 1, 9)).astype(int)
            pts = pts[idx2]
            t = t[idx2]
        return make_interp_spline(t, pts, k=3)(t_eval)
    except ImportError:
        return line


def deduplicate_line_indices(lines: List[np.ndarray], tol: float = 0.01,
                             ignore: Optional[set] = None) -> set:
    """Return indices of lines that represent the same physical boundary curve.

    Two lines are considered the same boundary when BOTH of their endpoints
    match within *tol* (forward or reversed).  Using only the two endpoints
    (not all interior sample points) handles the case where the same physical
    boundary is sampled at different parametric speeds by adjacent patches --
    interior points then don't correspond index-for-index even though the
    curve is geometrically identical.

    tol=0.01 physical units catches:
    - Exact duplicates from declared interfaces (gap=0, diff ~1e-13)
    The previous tol=0.5 was too aggressive: for the hexagon geometry
    (circumradius 1, patch width ~0.866) iso-lines are spaced ~0.054 apart,
    so tol=0.5 falsely removed all interior mesh lines.

    Since 2026-10-01 the whole curve must coincide as well: every point of the
    second line must lie within 2e-3 of the bounding-box diagonal of the first
    line (as a polyline). Two boundary curves of a non-conforming interface share
    both corners but differ in between (joystick patches 0/14 and 1/17: up to
    0.55 apart); both are then kept, so that the gap is drawn.

    Indices in *ignore* are not drawn at all; they are returned as skipped and
    never act as the kept copy of a duplicate.
    """
    skip = set(ignore or ())
    n_ignored = len(skip)
    n = len(lines)
    if n:
        _pts = np.vstack(lines)
        curve_tol = 2e-3 * float(np.linalg.norm(_pts.max(axis=0) - _pts.min(axis=0)))
    else:
        curve_tol = tol

    def _same_curve(a: np.ndarray, b: np.ndarray) -> bool:
        return max(_closest_point_on_polyline(a, p)[1] for p in b) < curve_tol
    for i in range(n):
        if i in skip:
            continue
        li = lines[i]
        li_first = li[0]
        li_last = li[-1]
        for j in range(i + 1, n):
            if j in skip:
                continue
            lj = lines[j]
            lj_first = lj[0]
            lj_last = lj[-1]
            # Forward: endpoints align in same order
            if (np.max(np.abs(li_first - lj_first)) < tol and
                    np.max(np.abs(li_last - lj_last)) < tol):
                if _same_curve(li, lj):
                    skip.add(j)
            # Reversed: second line runs the opposite direction
            elif (np.max(np.abs(li_first - lj_last)) < tol and
                    np.max(np.abs(li_last - lj_first)) < tol):
                if _same_curve(li, lj):
                    skip.add(j)
    print(f"[dedup] {len(skip) - n_ignored} duplicate lines suppressed out of {n}"
          + (f" ({n_ignored} ignored)" if n_ignored else ""))
    return skip


def validate_mesh_lines(lines: List[np.ndarray],
                        patch_ids: List[int],
                        directions: List[str],
                        endpoint_tol: float = 1e-6) -> Dict[str, object]:
    """Compute structural diagnostics for an exported mesh file.

    The report is intentionally lightweight and robust:
    - per-patch/per-direction line counts,
    - duplicate-curve estimate via endpoint signatures,
    - basic point-count range across lines.
    """
    per_patch_dir = Counter((p, d) for p, d in zip(patch_ids, directions))

    def _q(pt: np.ndarray) -> Tuple[int, int]:
        return (int(round(float(pt[0]) / endpoint_tol)),
                int(round(float(pt[1]) / endpoint_tol)))

    endpoint_signatures = []
    point_counts = []
    for line in lines:
        if len(line) == 0:
            continue
        point_counts.append(len(line))
        a = _q(line[0])
        b = _q(line[-1])
        sig = (a, b) if a <= b else (b, a)
        endpoint_signatures.append(sig)

    sig_counts = Counter(endpoint_signatures)
    duplicate_groups = sum(1 for v in sig_counts.values() if v > 1)
    duplicate_lines = sum(v - 1 for v in sig_counts.values() if v > 1)

    return {
        'total_lines': len(lines),
        'unique_endpoint_signatures': len(sig_counts),
        'duplicate_endpoint_groups': duplicate_groups,
        'duplicate_endpoint_lines': duplicate_lines,
        'min_points_per_line': min(point_counts) if point_counts else 0,
        'max_points_per_line': max(point_counts) if point_counts else 0,
        'per_patch_direction_counts': dict(sorted(per_patch_dir.items(), key=lambda item: (item[0][0], item[0][1]))),
    }


def print_mesh_validation(report: Dict[str, object]) -> None:
    """Print mesh export diagnostics in a compact, script-friendly form."""
    print("\n" + "=" * 60)
    print("MESH EXPORT VALIDATION")
    print("=" * 60)
    print(f"Total lines:                    {report['total_lines']}")
    print(f"Unique endpoint signatures:     {report['unique_endpoint_signatures']}")
    print(f"Duplicate endpoint groups:      {report['duplicate_endpoint_groups']}")
    print(f"Duplicate endpoint extra lines: {report['duplicate_endpoint_lines']}")
    print(f"Points per line:                min={report['min_points_per_line']}, max={report['max_points_per_line']}")
    print("\nPer patch/direction line counts:")
    for (patch, direction), count in report['per_patch_direction_counts'].items():
        print(f"  patch={patch:2d} dir={direction:>7s} : {count:4d}")
    print("=" * 60 + "\n")


def load_lines_from_file(filepath: str) -> Tuple[List[np.ndarray], List[int], List[str]]:
    """! Load grid lines from a mesh file exported by G+Smo.
    
    Reads a text file containing visualization mesh data in the format:
    
    # Comment lines (ignored)
    x y patch_id direction
    x y patch_id direction
    ...
    (blank line separates different grid lines)
    
    The function parses both old format (x y) and new format (x y patch_id direction).
    
    @param filepath (str): Absolute path to the mesh data file.
    
    @return tuple: A tuple containing:
        - lines (List[np.ndarray]): List of line coordinate arrays, each array has shape (n_points, 2)
                                     where each row is [x, y]
        - patch_ids (List[int]): Patch ID for each line
        - directions (List[str]): Direction character for each line ('u', 'v', or 'unknown')
    
    @throws FileNotFoundError: If the specified file does not exist.
    @throws ValueError: If the file contains invalid numeric data.
    
    @note Lines are separated by blank lines in the input file.
    @note Comment lines starting with '#' are automatically skipped.
    
    @par Example:
    @code
    lines, patches, dirs = load_lines_from_file("mesh_attempt53.txt")
    print(f"Loaded {len(lines)} grid lines from {len(set(patches))} patches")
    @endcode
    """
    with open(filepath, 'r') as f:
        raw_lines = f.readlines()

    lines = []
    patch_ids = []
    directions = []
    
    current_coords = []
    current_patch = -1
    current_dir = 'unknown'

    for line in raw_lines:
        stripped = line.strip()
        
        # Skip empty lines - they separate different grid lines
        if not stripped:
            if current_coords:
                lines.append(np.array(current_coords, dtype=float))
                patch_ids.append(current_patch)
                directions.append(current_dir)
                current_coords = []
                current_patch = -1
                current_dir = 'unknown'
            continue
        
        # Skip comment lines
        if stripped.startswith('#'):
            continue
        
        # Parse data line
        parts = stripped.split()
        
        if len(parts) >= 2:
            x = float(parts[0])
            y = float(parts[1])
            current_coords.append([x, y])
            
            # Extract patch ID and direction if available (new format)
            if len(parts) >= 3:
                current_patch = int(parts[2])
            if len(parts) >= 4:
                current_dir = parts[3]

    # Don't forget the last line if file doesn't end with blank line
    if current_coords:
        lines.append(np.array(current_coords, dtype=float))
        patch_ids.append(current_patch)
        directions.append(current_dir)

    return lines, patch_ids, directions


def load_patch_metadata(filepath: str) -> Dict[int, Dict[str, np.ndarray]]:
    """! Load per-patch visualization metadata exported by G+Smo.

    The companion metadata file has the format:

    patch mirrored jac_det center_x center_y u_dir_x u_dir_y v_dir_x v_dir_y

    @param filepath (str): Absolute path to the patch metadata file.

    @return dict: Mapping patch_id -> metadata dictionary.
    """
    metadata: Dict[int, Dict[str, np.ndarray]] = {}

    if not os.path.exists(filepath):
        return metadata

    with open(filepath, 'r') as f:
        raw_lines = f.readlines()

    for line in raw_lines:
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            continue

        parts = stripped.split()
        if len(parts) < 9:
            continue

        patch = int(parts[0])
        mirrored = bool(int(parts[1]))
        jac_det = float(parts[2])
        center = np.array([float(parts[3]), float(parts[4])], dtype=float)
        u_dir = np.array([float(parts[5]), float(parts[6])], dtype=float)
        v_dir = np.array([float(parts[7]), float(parts[8])], dtype=float)

        metadata[patch] = {
            'mirrored': mirrored,
            'jac_det': jac_det,
            'center': center,
            'u_dir': u_dir,
            'v_dir': v_dir,
        }

    return metadata


def _find_closest_boundary_line(lines: List[np.ndarray],
                                patch_ids: List[int],
                                target_patch: int,
                                target_midpoint: np.ndarray,
                                max_dist: float = 2.0) -> Optional[int]:
    """Return the index of the grid line from target_patch whose physical midpoint is closest to target_midpoint."""
    best_idx = None
    best_dist = max_dist
    for i, (line, pid) in enumerate(zip(lines, patch_ids)):
        if pid != target_patch:
            continue
        mid = line[len(line) // 2]
        dist = np.linalg.norm(mid - target_midpoint)
        if dist < best_dist:
            best_dist = dist
            best_idx = i
    return best_idx


def _closest_point_on_polyline(poly: np.ndarray, pt: np.ndarray) -> Tuple[np.ndarray, float]:
    """Closest point to *pt* on the polyline *poly* (segments, not only vertices)."""
    if len(poly) == 1:
        return poly[0].copy(), float(np.linalg.norm(poly[0] - pt))
    a = poly[:-1]
    ab = poly[1:] - a
    denom = np.einsum('ij,ij->i', ab, ab)
    t = np.einsum('ij,ij->i', pt - a, ab) / np.where(denom > 0.0, denom, 1.0)
    t = np.clip(t, 0.0, 1.0)
    proj = a + t[:, None] * ab
    d = np.linalg.norm(proj - pt, axis=1)
    k = int(d.argmin())
    return proj[k], float(d[k])


def fix_interface_visualization(lines: List[np.ndarray],
                                patch_ids: List[int],
                                interface_metadata: List[Dict[str, object]],
                                degree: Optional[int] = None,
                                side_lines: Optional[Dict[Tuple[int, str], int]] = None) -> set:
    """Eliminate visual C0 seams at all declared interfaces.

    For each interface:
    1. Snap the endpoints of patch-B iso-lines that end on the interface to the
       CLOSEST POINT of patch-A's boundary curve (the per-element polynomial of
       upsample_iso_lines when *degree* is known, else the polyline). An endpoint
       then moves by at most the interface gap.
       (Until 2026-10-01 the endpoint was mapped by SAMPLE INDEX, t = k_b/(n_b-1)
       -> k_a = t (n_a-1). Sample index is linear in the parameter only if all
       elements of both boundary lines have the same size; on a hierarchical mesh
       they do not, so endpoints were moved by up to one element (about 1 unit on
       the joystick) while the rest of the line stayed put, and the per-element
       polynomial of upsample_iso_lines turned that jump into a hook at the end of
       the line.)
    2. Replace patch-B's boundary curve with a copy of patch-A's so that
       deduplicate_line_indices (tol=0.01) suppresses the duplicate, eliminating
       the boundary-edge seam.

    The gap annotations in draw_interface_diagnostics still show the true numerical
    gap from the binary's _interface_meta.txt so diagnostic info is preserved.

    Interfaces whose two boundary curves are really apart (largest distance above
    2e-3 of the bounding-box diagonal) are NOT stitched: both curves are drawn as
    they are, so that a gap in the geometry stays visible instead of being hidden
    (and instead of bending the iso-lines that end on it). A warning names them.

    Returns the set of patch pairs (frozensets) whose interface was left
    unstitched, so that fix_corner_gaps leaves their line ends alone as well.

    *side_lines* maps (patch, side) to the index of the full interface line (from
    classify_mesh_lines); when given, those lines are used as the two boundary
    curves instead of the line whose midpoint is closest to the metadata midpoint.
    """
    unstitched = set()
    if lines:
        _pts = np.vstack(lines)
        vis_tol = 2e-3 * float(np.linalg.norm(_pts.max(axis=0) - _pts.min(axis=0)))
    else:
        vis_tol = 0.0
    for info in interface_metadata:
        gap = info['gap']

        # Find both boundary curves BEFORE any modification
        if side_lines is not None:
            idx_a = side_lines.get((info['patch_a'], info['side_a']))
            idx_b = side_lines.get((info['patch_b'], info['side_b']))
        else:
            idx_a = _find_closest_boundary_line(lines, patch_ids, info['patch_a'], info['midpoint_a'])
            idx_b = _find_closest_boundary_line(lines, patch_ids, info['patch_b'], info['midpoint_b'])

        if idx_a is None or idx_b is None:
            print(f"[fix-interface] WARNING: could not locate boundary lines for "
                  f"{info['patch_a']}:{info['side_a']} <-> {info['patch_b']}:{info['side_b']}")
            continue

        boundary_a = lines[idx_a]
        boundary_b_orig = lines[idx_b].copy()  # Original B boundary for parametric look-up
        reversed_ori = info['reversed']
        # Endpoints of patch-B iso-lines lie ON boundary_b_orig (within floating-point),
        # so projecting onto boundary_b_orig is reliable with a small tolerance.
        snap_tol = max(gap * 5.0, 1e-3)

        # --- Step 1: snap iso-line endpoints on the interface to the closest point of A's curve ---
        curve_a, curve_b = boundary_a, boundary_b_orig
        if degree is not None and degree >= 2:
            curve_a = upsample_iso_lines([boundary_a], degree, n_eval=50)[0]
            curve_b = upsample_iso_lines([boundary_b_orig], degree, n_eval=50)[0]
        separation = max(_closest_point_on_polyline(curve_a, p)[1] for p in curve_b)
        if separation > vis_tol:
            print(f"[fix-interface] WARNING: {info['patch_a']}:{info['side_a']} <-> "
                  f"{info['patch_b']}:{info['side_b']}: the boundary curves are up to "
                  f"{separation:.4g} apart (> {vis_tol:.3g}); drawn unstitched")
            unstitched.add(frozenset((info['patch_a'], info['patch_b'])))
            continue
        n_snapped = 0
        for i, (line, pid) in enumerate(zip(lines, patch_ids)):
            if pid != info['patch_b'] or i == idx_b:
                continue
            for endpt_pos in (0, -1):
                pt = line[endpt_pos]
                # Is the endpoint on the B-side interface?
                dists_b = np.linalg.norm(boundary_b_orig - pt, axis=1)
                if dists_b.min() >= snap_tol:
                    continue  # Endpoint is not at the B-side interface
                q, _ = _closest_point_on_polyline(curve_a, pt)
                line[endpt_pos] = q
                n_snapped += 1

        # --- Step 2: replace patch-B boundary curve with patch-A's ---
        # A plain copy, also when the sample counts differ. (Until 2026-10-02 A's
        # samples were interpolated LINEARLY onto B's count: a coarse side with
        # 3 samples became a polyline of straight pieces, which no longer matched
        # A's curve, so both were drawn - visible on the Yeti at 1/6 and 3/7.)
        lines[idx_b] = boundary_a.copy()

        print(f"[fix-interface] {info['patch_a']}:{info['side_a']} -> "
              f"{info['patch_b']}:{info['side_b']} | gap={gap:.3e} | "
              f"snapped {n_snapped} endpoints (tol={snap_tol:.3f})")
    return unstitched


def fix_corner_gaps(lines: List[np.ndarray], patch_ids: List[int], tol: float = 0.3,
                    skip_pairs: Optional[set] = None) -> None:
    """Snap corner vertices shared between patches that have no declared edge interface.

    Iterates all pairs of lines from different patches and checks whether any
    endpoint-to-endpoint distance is within *tol*.  When found, the second
    line's endpoint is moved to the first's position, closing the visual gap.
    tol=0.3 is well below the smallest inter-line spacing (~5 units) so false
    positives are not a concern for TV-scale geometries.
    Pairs of patches in *skip_pairs* (interfaces drawn unstitched by
    fix_interface_visualization) are left alone.
    """
    skip_pairs = skip_pairs or set()
    n = len(lines)
    n_snapped = 0
    for i in range(n):
        if patch_ids[i] < 0:
            continue
        for j in range(i + 1, n):
            if patch_ids[j] < 0 or patch_ids[j] == patch_ids[i]:
                continue
            if frozenset((patch_ids[i], patch_ids[j])) in skip_pairs:
                continue
            for ei in (0, -1):
                for ej in (0, -1):
                    d = np.linalg.norm(lines[i][ei] - lines[j][ej])
                    if d < tol and d > 1e-9:
                        lines[j][ej] = lines[i][ei].copy()
                        n_snapped += 1
    if n_snapped:
        print(f"[fix-corners] snapped {n_snapped} corner endpoint(s) (tol={tol})")


def load_interface_metadata(filepath: str) -> List[Dict[str, object]]:
    """! Load per-interface visualization metadata exported by G+Smo."""
    metadata: List[Dict[str, object]] = []

    if not os.path.exists(filepath):
        return metadata

    with open(filepath, 'r') as f:
        raw_lines = f.readlines()

    for line in raw_lines:
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            continue

        parts = stripped.split()
        if len(parts) < 16:
            continue

        metadata.append({
            'patch_a': int(parts[0]),
            'patch_b': int(parts[1]),
            'side_a': parts[2],
            'side_b': parts[3],
            'reversed': bool(int(parts[4])),
            'mirrored_a': bool(int(parts[5])),
            'mirrored_b': bool(int(parts[6])),
            'gap': float(parts[7]),
            'midpoint_a': np.array([float(parts[8]), float(parts[9])], dtype=float),
            'tangent_a': normalized(np.array([float(parts[10]), float(parts[11])], dtype=float)),
            'midpoint_b': np.array([float(parts[12]), float(parts[13])], dtype=float),
            'tangent_b': normalized(np.array([float(parts[14]), float(parts[15])], dtype=float)),
        })

    return metadata


def load_mesh_metadata(filepath: str) -> Optional[int]:
    """Read degree from *_mesh_meta.txt. Returns None if file missing."""
    if not os.path.exists(filepath):
        return None
    with open(filepath) as f:
        for line in f:
            s = line.strip()
            if s.startswith('#') or not s:
                continue
            parts = s.split()
            if len(parts) == 2 and parts[0] == 'degree':
                try:
                    return int(parts[1])
                except ValueError:
                    pass
    return None


def load_boxes_file(filepath: str) -> Optional[Dict[int, List[Tuple[int, int, int, int, int]]]]:
    """Read *_boxes.txt (patch level u0 v0 u1 v1 ix0 iy0 ix1 iy1) in file order.

    Returns {patch: [(level, ix0, iy0, ix1, iy1), ...]} or None if the file is missing.
    """
    if not os.path.exists(filepath):
        return None
    boxes: Dict[int, List[Tuple[int, int, int, int, int]]] = {}
    with open(filepath) as f:
        for line in f:
            s = line.strip()
            if not s or s.startswith('#'):
                continue
            t = s.split()
            if len(t) < 10:
                continue
            boxes.setdefault(int(t[0]), []).append(
                (int(t[1]), int(t[6]), int(t[7]), int(t[8]), int(t[9])))
    return boxes


def classify_mesh_lines(lines: List[np.ndarray],
                        patch_ids: List[int],
                        directions: List[str],
                        boxes: Optional[Dict[int, List[Tuple[int, int, int, int, int]]]],
                        degree: Optional[int],
                        interface_metadata: Optional[List[Dict[str, object]]]
                        ) -> Optional[List[Tuple[str, Optional[str]]]]:
    """Recover the parametric position of every exported line.

    Replays the line order of the C++ export (generateParametricGrid in
    poissonTHB_example.cpp): for every patch and every box not covered by a finer
    box, the u-lines from iy0 to iy1 and then the v-lines from ix0 to ix1, sampled
    with `degree` points per finest cell; a line on the parametric boundary carries
    n^2 instead of n points. After all boxes follow one full-length line per patch
    side that belongs to an interface, in the order of the interface metadata.

    Returns, per line, ('interior', None), ('edge', side) for a box edge on the
    patch side `side` (U0, U1, V0, V1), or ('iface', side) for a full interface
    side. Every replayed line is checked against the file (patch, direction,
    number of points); on any mismatch None is returned and the caller falls back
    to the geometric heuristic.

    (Until 2026-10-02 boundary lines were guessed per (patch, direction) as the two
    lines with the farthest midpoints. On a hierarchical mesh a patch side consists
    of several box edges, so only one piece of it was drawn bold, the rest thin,
    and sometimes an interior line was drawn bold instead.)
    """
    if not boxes or not degree or degree < 1:
        return None
    s = degree
    info: List[Tuple[str, Optional[str]]] = []
    expected: List[Tuple[int, str, int]] = []
    pmax: Dict[int, int] = {}

    def _covered(bl, k):
        lv, x0, y0, x1, y1 = bl[k]
        for j, (ol, a0, b0, a1, b1) in enumerate(bl):
            if j == k or ol <= lv:
                continue
            sc = 1 << (ol - lv)
            if a0 <= x0 * sc and a1 >= x1 * sc and b0 <= y0 * sc and b1 >= y1 * sc:
                return True
        return False

    for p in sorted(boxes):
        bl = boxes[p]
        pmax[p] = max(b[0] for b in bl)
        nfin = 1 << pmax[p]
        for k, (lv, x0, y0, x1, y1) in enumerate(bl):
            if _covered(bl, k):
                continue
            sf = 1 << (pmax[p] - lv)
            X0, Y0, X1, Y1 = x0 * sf, y0 * sf, x1 * sf, y1 * sf
            for fy in range(Y0, Y1 + 1, sf):
                n = (X1 - X0) * s + 1
                side = 'V0' if fy == 0 else ('V1' if fy == nfin else None)
                expected.append((p, 'u', n * n if side else n))
                info.append(('edge', side) if side else ('interior', None))
            for fx in range(X0, X1 + 1, sf):
                n = (Y1 - Y0) * s + 1
                side = 'U0' if fx == 0 else ('U1' if fx == nfin else None)
                expected.append((p, 'v', n * n if side else n))
                info.append(('edge', side) if side else ('interior', None))

    emitted = set()
    for itf in interface_metadata or []:
        for p, side in ((itf['patch_a'], itf['side_a']), (itf['patch_b'], itf['side_b'])):
            if p not in pmax or (p, side) in emitted:
                continue
            emitted.add((p, side))
            expected.append((p, 'v' if side in ('U0', 'U1') else 'u', (1 << pmax[p]) * s + 1))
            info.append(('iface', side))

    if len(expected) != len(lines):
        print(f"[classify] {len(lines)} lines in the file, {len(expected)} replayed; "
              f"falling back to the boundary heuristic")
        return None
    for i, (p, d, n) in enumerate(expected):
        if patch_ids[i] != p or directions[i] != d or len(lines[i]) != n:
            print(f"[classify] line {i} does not match the replay (patch {patch_ids[i]}/{p}, "
                  f"dir {directions[i]}/{d}, points {len(lines[i])}/{n}); "
                  f"falling back to the boundary heuristic")
            return None
    n_edge = sum(1 for k, _ in info if k == 'edge')
    n_iface = sum(1 for k, _ in info if k == 'iface')
    print(f"[classify] all {len(lines)} lines matched: {n_edge} box edges on patch sides, "
          f"{n_iface} full interface sides")
    return info


def upsample_iso_lines(lines: List[np.ndarray], degree: int,
                       n_eval: int = 50) -> List[np.ndarray]:
    """Replace each iso-line with a smooth degree-p curve.

    C++ outputs degree+1 sample points per Bezier element (index cell), spaced
    uniformly in the local parameter.  For each element we fit an exact degree-p
    polynomial through those points and evaluate it at n_eval values, giving a
    smooth curve that matches the true B-spline geometry.

    Points per line = n_elements * degree + 1, so element boundaries are at
    indices 0, degree, 2*degree, ...
    """
    if degree < 2:
        return lines
    upsampled = []
    for line in lines:
        n = len(line)
        if n < degree + 1:
            upsampled.append(line)
            continue
        # Element boundaries: index 0, degree, 2*degree, ...
        n_elements = (n - 1) // degree
        if n_elements < 1 or (n - 1) % degree != 0:
            # Not an exact multiple — fall back unchanged
            upsampled.append(line)
            continue
        t_ctrl = np.linspace(0.0, 1.0, degree + 1)
        t_dense = np.linspace(0.0, 1.0, n_eval)
        segments = []
        for e in range(n_elements):
            i0 = e * degree
            pts = line[i0: i0 + degree + 1]  # (degree+1, 2)
            cx = np.polyfit(t_ctrl, pts[:, 0], degree)
            cy = np.polyfit(t_ctrl, pts[:, 1], degree)
            seg = np.column_stack([np.polyval(cx, t_dense), np.polyval(cy, t_dense)])
            # Drop the first point of each segment except the first so segments join exactly
            if e > 0:
                seg = seg[1:]
            segments.append(seg)
        upsampled.append(np.vstack(segments))
    return upsampled


def load_boxes_phys_file(filepath: str) -> List[Dict]:
    """Load physical box corners from *_boxes_phys.txt exported by C++.

    Returns a list of dicts: {patch, level, corners} where corners is (4,2) array
    in counter-clockwise order (SW, SE, NE, NW).
    """
    boxes = []
    print(f"[boxes] Looking for: {filepath}")
    if not os.path.exists(filepath):
        print(f"[boxes] WARNING: file not found — no level overlay will be drawn")
        return boxes
    with open(filepath) as f:
        for line in f:
            s = line.strip()
            if not s or s.startswith('#'):
                continue
            parts = s.split()
            if len(parts) < 10:
                continue
            patch = int(parts[0])
            level = int(parts[1])
            corners = np.array([float(x) for x in parts[2:10]], dtype=float).reshape(4, 2)
            boxes.append({'patch': patch, 'level': level, 'corners': corners})
    print(f"[boxes] Loaded {len(boxes)} physical box quads from {os.path.basename(filepath)}")
    return boxes


def draw_boxes_physical(ax, boxes: List[Dict]) -> List:
    """Overlay THB-spline cells as semi-transparent level-coloured quads.

    Returns a list of (handle, label) tuples to be appended to the main legend.
    """
    if not boxes:
        return []
    from matplotlib.patches import Polygon
    from matplotlib.collections import PatchCollection

    all_levels = sorted(set(b['level'] for b in boxes))
    # One distinct colour per level; use a qualitative map
    cmap = plt.cm.get_cmap('Set1', max(len(all_levels), 2))
    level_colors = {lv: cmap(i) for i, lv in enumerate(all_levels)}

    legend_handles = []
    for lv in all_levels:
        col_rgba = level_colors[lv]
        face = col_rgba[:3]
        polys = [Polygon(b['corners'], closed=True)
                 for b in boxes if b['level'] == lv]
        if not polys:
            continue
        pc = PatchCollection(polys, alpha=1.0, facecolor='none',
                             edgecolor=face, linewidth=1.2, zorder=3)
        ax.add_collection(pc)
        ax.autoscale_view()
        from matplotlib.patches import Patch
        legend_handles.append(Patch(facecolor=face, alpha=0.5, label=f'Level {lv} cells'))

    return legend_handles


